def derive_l1():
    """Выводит поток уровня 1 из границ уровня 2 + ручные потоки. Возвращает множество (src, dst, label)."""
    flows = set()
    for parent, spec in L2.items():
        inner = set(spec["inner"])
        for src, dst, label, l1 in spec["flows"]:
            s_in, d_in = src in inner, dst in inner
            if s_in and d_in:
                continue
            if not (s_in or d_in):
                raise ValueError(f"{parent}: поток вне процесса {src}->{dst}")
            if l1 is None:
                raise ValueError(f"{parent}: граничный поток без метки уровня 1: {src}->{dst} {label}")
            flows.add((parent if s_in else src, parent if d_in else dst, l1))
    for s, d, l in L1_MANUAL:
        flows.add((s, d, l))
    return flows


def check():
    errs = []
    l1 = derive_l1()
    node_ids = set(ENTITIES) | set(STORES) | set(PROCESSES)
    for s, d, l in l1:
        for x in (s, d):
            if x not in node_ids:
                errs.append(f"L1: неизвестный узел {x}")
    # каждый процесс имеет вход и выход
    for p in PROCESSES:
        if not any(d == p for _, d, _ in l1): errs.append(f"L1: у {p} нет входящих потоков")
        if not any(s == p for s, _, _ in l1): errs.append(f"L1: у {p} нет исходящих потоков")
    # запрещены потоки хранилище-хранилище и сущность-хранилище, сущность-сущность
    for s, d, l in l1:
        if s.startswith("D") and d.startswith("D"): errs.append(f"L1: хранилище→хранилище {s}->{d}")
        if (s.startswith("E") and d.startswith("D")) or (s.startswith("D") and d.startswith("E")):
            errs.append(f"L1: сущность↔хранилище {s}->{d}")
        if s.startswith("E") and d.startswith("E"): errs.append(f"L1: сущность→сущность {s}->{d}")
    # межпроцессные потоки между процессами, имеющими L2, должны совпадать с обеих сторон
    for p, spec in L2.items():
        inner = set(spec["inner"])
        for q, spec2 in L2.items():
            if p >= q: continue
            a = {(parent_or(p, s, inner), parent_or(p, d, inner), l1) for s, d, _, l1 in spec["flows"]
                 if (s in inner) != (d in inner) and (s == q or d == q) and l1}
            b = {(parent_or(q, s, set(spec2["inner"])), parent_or(q, d, set(spec2["inner"])), l1)
                 for s, d, _, l1 in spec2["flows"]
                 if (s in spec2["inner"]) != (d in spec2["inner"]) and (s == p or d == p) and l1}
            if a != b:
                errs.append(f"Баланс {p}/{q}: {sorted(a ^ b)}")
    # каждый внутренний процесс L2 имеет вход и выход
    for parent, spec in L2.items():
        for pid in spec["inner"]:
            if not any(d == pid for _, d, _, _ in spec["flows"]): errs.append(f"L2 {parent}: у {pid} нет входов")
            if not any(s == pid for s, _, _, _ in spec["flows"]): errs.append(f"L2 {parent}: у {pid} нет выходов")
        for s, d, _, _ in spec["flows"]:
            for x in (s, d):
                if x not in node_ids and x not in spec["inner"]:
                    errs.append(f"L2 {parent}: неизвестный узел {x}")
    # контекст: все внешние сущности покрыты
    ctx_e = {s for s, d, _ in CONTEXT_FLOWS if s.startswith("E")} | {d for s, d, _ in CONTEXT_FLOWS if d.startswith("E")}
    l1_e = {x for s, d, _ in l1 for x in (s, d) if x.startswith("E")}
    if ctx_e != l1_e: errs.append(f"Контекст vs L1: {ctx_e ^ l1_e}")
    # таблицы хранилищ существуют
    import sys
    sys.path.insert(0, "model")
    from schema_model import TABLE_BY_NAME, TABLES
    used = set()
    for k, (name, tabs) in STORES.items():
        for t in tabs:
            used.add(t)
            if t not in TABLE_BY_NAME: errs.append(f"{k}: нет таблицы {t}")
    missing = set(TABLE_BY_NAME) - used
    if missing: errs.append(f"Таблицы без хранилища DFD: {sorted(missing)}")
    return errs


def parent_or(parent, x, inner):
    return parent if x in inner else x


