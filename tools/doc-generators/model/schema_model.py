def C(name, typ, doc, *flags, fk=None, default=None, check=None):
    return dict(name=name, type=typ, doc=doc, flags=set(flags), fk=fk, default=default, check=check)


def T(name, domain, doc, cols, pk=None, uniques=(), indexes=(), checks=()):
    return dict(name=name, domain=domain, doc=doc, cols=cols, pk=pk, uniques=list(uniques),
                indexes=list(indexes), checks=list(checks))


