def des(key):
    d = {**DOCS, **LEGAL}[key]
    return f"{BASE} {d[0]}"

def new(key, subtitle=None, kind="espd"):
    d = {**DOCS, **LEGAL}[key]
    doc = Doc(des(key), d[1], kind=kind, subtitle=subtitle, year=YEAR)
    doc.refkey = key
    return doc

def ref(key):
    """Краткая ссылка на другой документ проекта: «Наименование» (обозначение)."""
    d = {**DOCS, **LEGAL}[key]
    return f"«{d[1]}» ({des(key)})"

def req_table(doc, group, key=None):
    rows = [[r["id"], r["text"], r["prio"], r["stage"], r["verify"]] for r in RQ.REQS if r["group"] == group]
    doc.table(RQ.GROUPS[group], ["Код", "Требование", "Пр.", "Этап", "Метод"], rows, widths=[2.7, 9.0, 1.0, 1.6, 1.7],
              key=key or "rq_" + group, font=11)
