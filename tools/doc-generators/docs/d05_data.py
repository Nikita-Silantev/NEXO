def fk_action(t, c):
    if not c["fk"]: return ""
    pk = set(t["pk"] or [])
    act = "CASCADE" if c["name"] in pk else ("SET NULL" if "nn" not in c["flags"] else "NO ACTION")
    return f"→ {c['fk']} ({act})"

def col_rows(t):
    rows = []
    for c in t["cols"]:
        fl = []
        if "pk" in c["flags"] or c["name"] in (t["pk"] or []): fl.append("PK")
        if "nn" in c["flags"] and "pk" not in c["flags"]: fl.append("NN")
        if "uq" in c["flags"]: fl.append("UQ")
        fk = fk_action(t, c)
        if fk: fl.append(fk)
        extra = []
        if c["default"]: extra.append("по умолч. " + str(c["default"]).replace("'", ""))
        if c["check"]: extra.append("CHECK: " + c["check"])
        ty = c["type"].replace("enum:", "")
        rows.append([c["name"], ty, "; ".join(fl) or "—", c["doc"] + (" [" + "; ".join(extra) + "]" if extra else "")])
    return rows


